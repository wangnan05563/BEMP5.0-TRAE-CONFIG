-- round5 E2E 数据现状查询（只读）
-- 1. 名单表 HNNX_M_CUST_SPECIAL_INFO 现状（OBJ_ID 留痕）
-- 2. 在途票据业务表探测与状态分布
-- ============================================================

-- 1. 名单表全量关键数据留痕
SELECT OBJ_ID, CUST_NM, CERT_TYPE, CERT_NO, LIST_CHRC, VLD_ST, DATA_SRC, DATA_DT, ACCT_NO
FROM HNNX_M_CUST_SPECIAL_INFO
ORDER BY OBJ_ID;

-- 2. 业务表存在性确认
SELECT TABLE_NAME FROM USER_TABLES
WHERE TABLE_NAME IN ('TE_REBUY_BILL','TE_SALE_BILL','TE_REDISC_SALE_BILL','TE_DISC_APPLY','TE_DISC_BILL','CE_DISC_APPLY')
ORDER BY TABLE_NAME;

-- 3. 转贴现买入在途票据（状态分布）
SELECT BILL_STATUS, COUNT(*) CNT FROM TE_REBUY_BILL GROUP BY BILL_STATUS ORDER BY BILL_STATUS;

-- 4. 转贴现卖出在途票据
SELECT BILL_STATUS, COUNT(*) CNT FROM TE_SALE_BILL GROUP BY BILL_STATUS ORDER BY BILL_STATUS;

-- 5. 再贴现卖出在途票据
SELECT BILL_STATUS, COUNT(*) CNT FROM TE_REDISC_SALE_BILL GROUP BY BILL_STATUS ORDER BY BILL_STATUS;
